// Consent versioning helper (gap I9)
// Tracks exactly which ToS/privacy-policy/disclaimer version a user accepted and when.
// Needed for PDPL compliance and for defending the "not legal advice" disclaimer.

import { db } from "@/lib/db";
import { audit } from "@/lib/audit";

// Current versions of all consent documents
// Bump these when the document text changes materially
export const CURRENT_CONSENT_VERSIONS = {
  terms_of_service: "1.0.0",
  privacy_policy: "1.0.0",
  not_legal_advice: "1.0.0",
  data_processing: "1.0.0",
} as const;

export type ConsentType = keyof typeof CURRENT_CONSENT_VERSIONS;

// Hash the document text so we can prove exactly what was accepted
async function hashText(text: string): Promise<string> {
  const encoder = new TextEncoder();
  const data = encoder.encode(text);
  const hashBuffer = await crypto.subtle.digest("SHA-256", data);
  return Array.from(new Uint8Array(hashBuffer))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

