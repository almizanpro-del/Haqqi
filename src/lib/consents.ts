export async function recordConsent(opts: {
  userId?: string;
  consentType: ConsentType;
  ipAddress?: string;
  userAgent?: string;
}): Promise<{ id: string; version: string; documentHash: string }> {
  const version = CURRENT_CONSENT_VERSIONS[opts.consentType];
  const text = CONSENT_TEXTS[opts.consentType].ar; // hash the Arabic text as canonical
  const documentHash = await hashText(text);

  const record = await db.consentRecord.create({
    data: {
      userId: opts.userId ?? null,
      consentType: opts.consentType,
      version,
      documentHash,
      ipAddress: opts.ipAddress ?? null,
      userAgent: opts.userAgent ?? null,
    },
  });

  await audit.consentAccepted(opts.userId, opts.consentType, version);

  return {
    id: record.id,
    version,
    documentHash,
  };
}

export async function getUserConsents(userId: string) {
  return db.consentRecord.findMany({
    where: { userId, withdrawnAt: null },
    orderBy: { acceptedAt: "desc" },
  });
}

export async function hasUserAcceptedLatestConsent(userId: string, consentType: ConsentType): Promise<boolean> {
  const latest = await db.consentRecord.findFirst({
    where: { userId, consentType, withdrawnAt: null },
    orderBy: { acceptedAt: "desc" },
  });
  return latest?.version === CURRENT_CONSENT_VERSIONS[consentType];
}
